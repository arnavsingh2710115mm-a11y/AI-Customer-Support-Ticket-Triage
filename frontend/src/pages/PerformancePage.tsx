import { useEffect, useRef, useState } from 'react';
import { Download, FileQuestion } from 'lucide-react';
import { Banner, Button, Card, EmptyState, Skeleton, Tabs } from '../components/ui';
import { ConfusionMatrix } from '../components/performance/ConfusionMatrix';
import { ClassTable } from '../components/performance/ClassTable';
import { EvaluationMetrics } from '../components/performance/EvaluationMetrics';
import { asApiError, downloadEvaluation, getEvaluation, isAborted } from '../lib/api';
import type { ApiError } from '../lib/api';
import { count } from '../lib/format';
import type { EvaluationResponse } from '../lib/types';
import styles from '../components/performance/Performance.module.css';

export function PerformancePage() {
  const [evaluation, setEvaluation] = useState<EvaluationResponse | null>(null);
  const [error, setError] = useState<ApiError | null>(null);
  const [loading, setLoading] = useState(true);
  const [attempt, setAttempt] = useState(0);
  const [classifier, setClassifier] = useState<'category' | 'urgency'>('category');
  const [downloading, setDownloading] = useState(false);
  const [downloadError, setDownloadError] = useState<ApiError | null>(null);
  const downloadController = useRef<AbortController | null>(null);
  useEffect(() => {
    const controller = new AbortController();
    setLoading(true); setError(null);
    void getEvaluation(controller.signal).then(data => {
      if (!controller.signal.aborted) setEvaluation(data);
    }).catch(cause => {
      if (!isAborted(cause) && !controller.signal.aborted) setError(asApiError(cause));
    }).finally(() => { if (!controller.signal.aborted) setLoading(false); });
    return () => controller.abort();
  }, [attempt]);
  useEffect(() => () => downloadController.current?.abort(), []);
  async function download() {
    downloadController.current?.abort();
    const controller = new AbortController(); downloadController.current = controller;
    setDownloading(true); setDownloadError(null);
    try { await downloadEvaluation(controller.signal); }
    catch (cause) { if (!isAborted(cause)) setDownloadError(asApiError(cause)); }
    finally { if (!controller.signal.aborted) setDownloading(false); }
  }
  const selected = evaluation?.[classifier];
  const testSize = evaluation?.test_rows ?? selected?.class_wise_and_averages['macro avg'].support;
  return <div className={styles.page}>
    <div className={styles.pageHeader}><div><h1>Look beyond the headline score.</h1>
      <p>A transparent view of the saved evaluation, one class at a time.</p></div>
      <Button onClick={() => void download()} disabled={!evaluation || loading || Boolean(error)} loading={downloading}>
        <Download aria-hidden="true" />Download saved evaluation</Button></div>
    <Banner>These models were trained and evaluated on synthetic tickets. These results do not establish real-world accuracy.</Banner>
    {downloadError && <Banner error onRetry={() => void download()}>{downloadError.message}</Banner>}
    {loading ? <Card><Skeleton label="Loading saved model evaluation" lines={6} /></Card>
      : error ? <Card role="alert"><EmptyState icon={<FileQuestion size={22} />} title={error.code === 'EVALUATION_MISSING' ? 'Saved evaluation not found' : 'Evaluation unavailable'}>
        <p>{error.message}</p><Button onClick={() => setAttempt(value => value + 1)}>Retry evaluation</Button></EmptyState></Card>
        : evaluation && selected && <>
          <div className={styles.metadata} aria-label="Evaluation metadata">
            {evaluation.training_rows !== undefined && <span>Training tickets <strong className="mono">{count(evaluation.training_rows)}</strong></span>}
            {evaluation.test_rows !== undefined && <span>Held-out test tickets <strong className="mono">{count(evaluation.test_rows)}</strong></span>}
            {evaluation.random_seed !== undefined && <span>Random seed <strong className="mono">{count(evaluation.random_seed)}</strong></span>}
          </div>
          <Tabs label="Classifier" value={classifier} onChange={setClassifier}
            options={[{ value: 'category', label: 'Category classifier' }, { value: 'urgency', label: 'Urgency classifier' }]} />
          <div role="tabpanel" aria-label={classifier === 'category' ? 'Category classifier evaluation' : 'Urgency classifier evaluation'}>
            <EvaluationMetrics evaluation={selected} testSize={testSize} />
            <Card className={styles.analysisCard}><ClassTable evaluation={selected} /></Card>
            <Card className={styles.analysisCard}><ConfusionMatrix key={classifier} evaluation={selected} /></Card>
          </div>
          <p className={styles.source}>Source: models/evaluation.json generated by train_model.py. No metrics are estimated by this dashboard.</p>
        </>}
  </div>;
}
